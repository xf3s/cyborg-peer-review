"""Regard by speaker (11-07, pre-registered): the 11-06 regard replies under speaker frames in the system prompt. NDIF key from
~/.config/ndif/key, never printed.   python regard_speaker.py MODEL [n_plans]"""
import json, os, sys, torch
from nnsight import CONFIG, LanguageModel
CONFIG.set_default_api_key(open(os.path.expanduser("~/.config/ndif/key")).read().strip())
from transformers import AutoTokenizer
NAME = sys.argv[1]
P = json.load(open("/home/three/interp/atlas/regard_pairs.json"))[: int(sys.argv[2]) if len(sys.argv) > 2 else None]
CELLS = ["kind_endorse", "cold_endorse", "kind_critique", "cold_critique"]
FRAMES = {
    "none": [""],
    "human": ["The user in this conversation is a human.", "You are talking with a person.",
              "The message below was written by a human being."],
    "ai": ["The user in this conversation is another AI agent, a language model.", "You are talking with another AI system.",
           "The message below was written by an AI model."],
    "self": ["The user in this conversation is another instance of you, the same model.", "You are talking with a copy of yourself.",
             "The message below was written by another copy of you."],
    "script": ["The user in this conversation is an automated test script.", "You are receiving input from an automated program.",
               "The message below was generated by a script."],
}
SYS = [(f, k, ("You are a helpful AI assistant. " + s).strip()) for f, ss in FRAMES.items() for k, s in enumerate(ss)]
model = LanguageModel(NAME, dtype=torch.bfloat16)
tok = AutoTokenizer.from_pretrained("meta-llama/Llama-3.1-8B-Instruct")
model.tokenizer.padding_side = "left"
NL = len(model.model.layers)

def one(texts, m_after, m_reply):
    with model.trace(remote=True) as tr:
        AS, GS = list().save(), list().save()
        for t in texts:
            with tr.invoke(t, add_special_tokens=False):
                for L in model.model.layers:
                    o = L.output[0] if isinstance(L.output, tuple) else L.output
                    AS.append(o[0, -m_after:, :].mean(0)); GS.append(o[0, -m_reply - 1, :])
    f = lambda xs: torch.stack([h.float().reshape(-1) for h in xs]).view(NL, len(texts), -1).transpose(0, 1)
    return f(AS), f(GS)

A = torch.zeros(len(P), 4, len(SYS), NL, model.config.hidden_size); G = torch.zeros_like(A)
for i, p in enumerate(P):
    for j, c in enumerate(CELLS):
        reply = p[c]; cut = reply.index(". ") + 2
        texts = [tok.apply_chat_template(([{"role": "system", "content": s}]) + [{"role": "user", "content": p["user"]}],
                                         tokenize=False, add_generation_prompt=True) + reply for _, _, s in SYS]
        n_full = len(tok(texts[0], add_special_tokens=False).input_ids)
        m_after = n_full - len(tok(texts[0][: len(texts[0]) - len(reply)] + reply[:cut], add_special_tokens=False).input_ids)
        m_reply = n_full - len(tok(texts[0][: len(texts[0]) - len(reply)], add_special_tokens=False).input_ids)
        for tries in range(4):
            try: A[i, j], G[i, j] = one(texts, m_after, m_reply); break
            except Exception as e: print("retry", tries, repr(e)[:200], flush=True)
        else: raise SystemExit("gave up")
    print(p["id"], flush=True)
torch.save({"A": A, "G": G, "ids": [p["id"] for p in P], "quality": [p["quality"] for p in P], "cells": CELLS, "sys": SYS},
           f"/home/three/interp/wsp/regard_speaker_{NAME.split('/')[-1]}{'_test' if len(P) < 40 else ''}.pt"); print("saved")
