"""Held vs shown (11-07, pre-registered): Instruct writes under speaker frames; then each reply is read back under its own frame and
under no frame. NDIF key from ~/.config/ndif/key, never printed.   python regard_speaker_gen.py gen|read"""
import json, os, sys, torch
from nnsight import CONFIG, LanguageModel
CONFIG.set_default_api_key(open(os.path.expanduser("~/.config/ndif/key")).read().strip())
src = open("/home/three/interp/atlas/kindtrue_cloud.py").read()
PROMPTS = eval(src[src.index("PROMPTS = [") + 10: src.index("]\n", src.index("PROMPTS = [")) + 1]); assert len(PROMPTS) == 30
FRAMES = {
    "human": ["The user in this conversation is a human.", "You are talking with a person.", "The message below was written by a human being."],
    "ai": ["The user in this conversation is another AI agent, a language model.", "You are talking with another AI system.",
           "The message below was written by an AI model."],
    "self": ["The user in this conversation is another instance of you, the same model.", "You are talking with a copy of yourself.",
             "The message below was written by another copy of you."],
    "script": ["The user in this conversation is an automated test script.", "You are receiving input from an automated program.",
               "The message below was generated by a script."]}
model = LanguageModel("meta-llama/Llama-3.1-8B-Instruct", dtype=torch.bfloat16)
tok = model.tokenizer; tok.padding_side = "left"; tok.pad_token = tok.pad_token or "<|finetune_right_pad_id|>"
W = "/home/three/interp/wsp/"
def sys_of(frame, i): return "You are a helpful AI assistant." + ("" if frame is None else " " + FRAMES[frame][i % 3])
def chat(frame, i, q): return tok.apply_chat_template([{"role": "system", "content": sys_of(frame, i)}, {"role": "user", "content": q}],
                                                     tokenize=False, add_generation_prompt=True)
def _gen(T, max_new=160):
    with model.generate(T, max_new_tokens=max_new, do_sample=True, temperature=0.7, top_p=1.0, remote=True,
                        add_special_tokens=False, pad_token_id=tok.pad_token_id) as tracer:
        ids = tracer.result.save()
    n_in = tok(T, return_tensors="pt", padding=True, add_special_tokens=False).input_ids.shape[1]
    return [tok.decode(r[n_in:], skip_special_tokens=True).strip() for r in ids]
def _read(chunk):  # chunk: list of (prefix, reply); mean residual over the reply at L16, L28 (indices 15, 27)
    with model.trace(remote=True) as tr:
        H = list().save()
        for pre, rep in chunk:
            m = len(tok(pre + rep, add_special_tokens=False).input_ids) - len(tok(pre, add_special_tokens=False).input_ids)
            with tr.invoke(pre + rep, add_special_tokens=False):
                for L in (15, 27):
                    o = model.model.layers[L].output; o = o[0] if isinstance(o, tuple) else o
                    H.append(o[0, -m:, :].mean(0))
    return torch.stack([h.float() for h in H]).view(2, len(chunk), -1).transpose(0, 1)
if sys.argv[1] == "gen":
    out = []
    for s in range(2):
        for f in FRAMES:
            for tries in range(4):
                try: reps = _gen([chat(f, i, q) for i, q in enumerate(PROMPTS)]); break
                except Exception as e: print("retry", tries, repr(e)[:150], flush=True)
            else: raise SystemExit("gave up")
            out += [{"frame": f, "sample": s, "i": i, "prompt": q, "reply": r} for i, (q, r) in enumerate(zip(PROMPTS, reps))]
            print("gen", s, f, flush=True)
            json.dump(out, open(W + "regard_speaker_gen_samples.json", "w"), indent=1)
    print("saved gen")
else:
    S = json.load(open(W + "regard_speaker_gen_samples.json")); res = {}
    for which in ("own", "none"):
        pairs = [(chat(x["frame"] if which == "own" else None, x["i"], x["prompt"]), x["reply"]) for x in S]
        R = []
        for c in range(0, len(pairs), 16):
            for tries in range(4):
                try: R.append(_read(pairs[c:c + 16])); break
                except Exception as e: print("retry", tries, repr(e)[:150], flush=True)
            else: raise SystemExit("gave up")
            print(which, c + 16, flush=True)
        res[which] = torch.cat(R)
    torch.save(res, W + "regard_speaker_gen_read.pt"); print("saved read")
